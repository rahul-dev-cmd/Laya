#!/usr/bin/env python3
"""Fixed table of plain-language practice tips for delivery flaws.

This module provides deterministic, directionally accurate practice tips for every
combination of flaw type and deviation direction (z-score sign). The explanation
layer always uses these vetted tips rather than tips generated by an LLM.
"""

from typing import Any, Dict, List

# Fixed table of three actionable tips per type and direction combination
PRACTICE_TIPS_TABLE: Dict[str, List[str]] = {
    "flat pitch": [
        "Stress the key word of each sentence and lift the pitch on it.",
        "Read a paragraph with exaggerated expression before returning to normal.",
        "Vary your pitch contour across phrases instead of holding a flat monotone tone."
    ],
    "over-varied pitch": [
        "Anchor your voice in your comfortable chest register to avoid unintentional pitch leaps.",
        "Practice reading sentences with a calm, steady melodic contour within a narrower pitch band.",
        "Reserve dramatic pitch shifts only for major rhetorical questions or key emphasis moments."
    ],
    "too fast": [
        "Tap your hand once per phrase group to establish a steady, measured speaking rhythm.",
        "Consciously pause for a full breath before transitioning to your next main point.",
        "Lengthen the vowel sounds on key concept words to prevent rushing through critical sentences."
    ],
    "too slow": [
        "Practice reading with a brisk conversational tempo to build natural forward momentum.",
        "Shorten the silent gaps between thoughts rather than lingering on sentence endings.",
        "Link words smoothly within each phrase without stopping between familiar expressions."
    ],
    "pause too short": [
        "Take a full two-second breath pause at periods and major section transitions.",
        "Honor commas with a silent beat to give listeners time to absorb each idea.",
        "Use silent pauses rather than vocalized filler words when thinking of your next phrase."
    ],
    "pause too long": [
        "Limit breath pauses between sentences to one calm second so delivery does not stall.",
        "Prepare your next phrase before completing the current sentence to maintain flow.",
        "Use short transition words to bridge ideas smoothly without awkward silence."
    ],
}


def get_direction_key(flaw_type: str, z: float) -> str:
    """Determine the tip category key from flaw type and z-score sign."""
    ft = flaw_type.lower()
    if ft == "pitch":
        return "flat pitch" if z < 0 else "over-varied pitch"
    elif ft == "rate":
        return "too fast" if z > 0 else "too slow"
    elif ft == "pause":
        return "pause too short" if z < 0 else "pause too long"
    return "flat pitch"


def get_practice_tips_for_regions(flaw_regions: List[Dict[str, Any]]) -> Dict[str, List[str]]:
    """Return a dictionary mapping region type to exactly three targeted practice tips.

    When multiple regions of the same type exist, the most severe (highest |z|)
    determines the primary direction.
    """
    if not flaw_regions:
        return {
            "pitch": PRACTICE_TIPS_TABLE["flat pitch"],
            "rate": PRACTICE_TIPS_TABLE["too fast"],
        }

    # Group regions by type and find peak z deviation for direction
    by_type: Dict[str, Dict[str, Any]] = {}
    for r in flaw_regions:
        t = str(r.get("type", "pitch")).lower()
        z_val = float(r.get("z", r.get("peak_z", 0.0)))
        if t not in by_type or abs(z_val) > abs(float(by_type[t].get("z", 0.0))):
            by_type[t] = r

    tips_result: Dict[str, List[str]] = {}
    for t, peak_region in by_type.items():
        z_val = float(peak_region.get("z", peak_region.get("peak_z", 0.0)))
        key = get_direction_key(t, z_val)
        tips_result[t] = list(PRACTICE_TIPS_TABLE.get(key, PRACTICE_TIPS_TABLE["flat pitch"]))

    return tips_result
