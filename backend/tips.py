def is_hindi_language(language: str) -> bool:
    """Check if the provided language identifier is Hindi or Hinglish."""
    lang = (language or "").strip().lower()
    return lang in ("hi", "hindi", "hi-in", "hinglish")


def get_direction_key(flaw_type: str, z: float) -> str:
    """Determine the tip category key from flaw type and z-score sign."""
    ft = flaw_type.lower()
    if ft == "pitch":
        return "flat pitch" if z < 0 else "over-varied pitch"
    elif ft == "rate":
        return "too fast" if z > 0 else "too slow"
    elif ft == "pause":
        return "pause too short" if z < 0 else "pause too long"
    return "flat pitch"


def get_practice_tips_for_regions(
    flaw_regions: List[Dict[str, Any]],
    language: str = "en",
) -> Dict[str, List[str]]:
    """Return a dictionary mapping region type to exactly three targeted practice tips.

    When multiple regions of the same type exist, the most severe (highest |z|)
    determines the primary direction. Supports English and plain Hindi tips (unreviewed by a native speaker).
    No AI model writes advice at run time.
    """
    is_hi = is_hindi_language(language)
    table = PRACTICE_TIPS_TABLE_HI if is_hi else PRACTICE_TIPS_TABLE

    if not flaw_regions:
        return {
            "pitch": list(table["flat pitch"]),
            "rate": list(table["too fast"]),
        }

    # Group regions by type and find peak z deviation for direction
    by_type: Dict[str, Dict[str, Any]] = {}
    for r in flaw_regions:
        t = str(r.get("type", "pitch")).lower()
        z_val = float(r.get("z", r.get("peak_z", 0.0)))
        if t not in by_type or abs(z_val) > abs(float(by_type[t].get("z", 0.0))):
            by_type[t] = r

    tips_result: Dict[str, List[str]] = {}
    for t, peak_region in by_type.items():
        z_val = float(peak_region.get("z", peak_region.get("peak_z", 0.0)))
        key = get_direction_key(t, z_val)
        tips_result[t] = list(table.get(key, table["flat pitch"]))

    return tips_result


def get_tips_speech_text(
    flaw_regions: List[Dict[str, Any]],
    language: str = "en",
) -> str:
    """Return concatenated practice tips for speech synthesis in the selected language.

    Deterministic tips (unreviewed by a native speaker) only. No AI model writes advice at run time.
    """
    tips_dict = get_practice_tips_for_regions(flaw_regions, language=language)
    all_tips: List[str] = []
    for tips_list in tips_dict.values():
        all_tips.extend(tips_list)
    return " ".join(all_tips)
